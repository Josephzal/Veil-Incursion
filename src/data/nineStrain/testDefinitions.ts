import type { UniversalBoonDefinition } from '../../types/nineStrain';

const TEST_PREFIX = 'TEST_STRAIN_';

function core(
  imprint: 'ARMAMENT' | 'DISCIPLINE' | 'INSTINCT' | 'CURRENT',
  strainId: UniversalBoonDefinition['strainId'],
  extras: Partial<UniversalBoonDefinition> = {},
): UniversalBoonDefinition {
  return {
    displayName: extras.displayName ?? `Test Core ${imprint}`,
    prerequisites: extras.prerequisites ?? {},
    exclusions: extras.exclusions ?? [],
    triggerGranularity: extras.triggerGranularity ?? 'ONCE_PER_ROOT_ACTION',
    eventSubscriptions: extras.eventSubscriptions ?? ['ROOT_ACTION_RESOLVED'],
    effectPrimitives: extras.effectPrimitives ?? [{ kind: 'RECORD_METRIC', metricKey: `hits_${imprint}` }],
    adapterNeeds: extras.adapterNeeds ?? [],
    procGuards: extras.procGuards ?? { blockSelfRecursion: true },
    bossTranslation: extras.bossTranslation ?? 'NONE',
    previewModel: extras.previewModel ?? 'OWNERSHIP',
    persistenceSchema: extras.persistenceSchema ?? 'test.core.v1',
    refinementHooks: extras.refinementHooks ?? [],
    playerFacingSummary: extras.playerFacingSummary ?? 'Test-only core.',
    secondaryStrainId: extras.secondaryStrainId,
    id: extras.id ?? `${TEST_PREFIX}CORE_${imprint}`,
    imprint,
    role: 'CORE',
    strainId,
    testOnly: true,
  };
}

