export function getKeepsakeDefinition(id: KeepsakeId): ExpeditionKeepsakeDefinition {
  return EXPEDITION_KEEPSAKE_REGISTRY[id];
}

export function listKeepsakeDefinitions(
  unlockedIds: readonly KeepsakeId[],
): ExpeditionKeepsakeDefinition[] {
  return unlockedIds
    .map((id) => EXPEDITION_KEEPSAKE_REGISTRY[id])
    .filter(Boolean)
    .sort((a, b) => a.displayPriority - b.displayPriority);
}

export function isKeepsakeId(value: string): value is KeepsakeId {
  return (ALL_KEEPSAKE_IDS as readonly string[]).includes(value);
}

export const DEFAULT_UNLOCKED_KEEPSAKE_IDS: readonly KeepsakeId[] = [...ALL_KEEPSAKE_IDS];
